package dev.uzumi.ime.voice

import org.junit.Assert.assertEquals
import org.junit.Test

/**
 * [VoiceFillerRemover]のフィラー除去規則と境界条件を検証する。
 * 期待出力はすべて具体的な確定文字列として固定し、規則から動的に計算しない。
 */
class VoiceFillerRemoverTest {
    /** 実機認識器出力の期待表V01〜V16がすべて期待出力と一致することを確認する。 */
    @Test
    fun matchesExpectationTableV01ToV16() {
        val cases = listOf(
            "V01" to (
                "えっと明日の打ち合わせはあの3時からでお願いします。" to
                    "明日の打ち合わせはあの3時からでお願いします。"
                ),
            "V02" to (
                "まあなんか最近ちょっとえ寝不足気味なんだよね。" to
                    "まあなんか最近ちょっと寝不足気味なんだよね。"
                ),
            "V03" to (
                "あの店のラーメンえ、また食べに行きたい。" to
                    "あの店のラーメン、また食べに行きたい。"
                ),
            "V04" to (
                "集合は駅の東口や西口にしよう。" to
                    "集合は駅の東口や西口にしよう。"
                ),
            "V05" to (
                "牛乳と卵とバナナを買ってきて、あやっぱりバナナはやめてリンゴにして。" to
                    "牛乳と卵とバナナを買ってきて、あやっぱりバナナはやめてリンゴにして。"
                ),
            "V06" to (
                "今週末は家で映画を見るつもり、さっき言ったのは無しで、今週末は実家に帰ります。" to
                    "今週末は家で映画を見るつもり、さっき言ったのは無しで、今週末は実家に帰ります。"
                ),
            "V07" to (
                "えっと会議の資料ってもう共有してもらいましたか？" to
                    "会議の資料ってもう共有してもらいましたか？"
                ),
            "V08" to (
                "予算はえ1人当たり3500円くらいで考えています。" to
                    "予算は1人当たり3500円くらいで考えています。"
                ),
            "V09" to (
                "え、来週のミーティングはGoogleミントじゃなくてZOOMでやります。" to
                    "来週のミーティングはGoogleミントじゃなくてZOOMでやります。"
                ),
            "V10" to (
                "Pixel 10 Proのカメラで撮った写真をあのGoogleフォトに上げておいたよ。" to
                    "Pixel 10 Proのカメラで撮った写真をあのGoogleフォトに上げておいたよ。"
                ),
            "V11" to (
                "その件、そのその件については確認してから返事します。" to
                    "その件、そのその件については確認してから返事します。"
                ),
            "V12" to (
                "えとか、あのみたいな言葉をフィラーと呼びます。" to
                    "えとか、あのみたいな言葉をフィラーと呼びます。"
                ),
            "V13" to (
                "えっと今日の報告ですえ、午前中はあの新しいキーボードの配置を試して、まあ大体問題なかったです。午後はえ音声入力の比較をする予定だったんですけど、端末の更新が入ったので明日いや明後日に回します。何かあればえっとチャットで連絡ください。" to
                    "今日の報告です、午前中はあの新しいキーボードの配置を試して、まあ大体問題なかったです。午後は音声入力の比較をする予定だったんですけど、端末の更新が入ったので明日いや明後日に回します。何かあればチャットで連絡ください。"
                ),
            "V14" to (
                "窓を開けて風を入れる。" to
                    "窓を開けて風を入れる。"
                ),
            "V15" to (
                "すみませんえ、明日の朝少し遅れていきます。" to
                    "すみません、明日の朝少し遅れていきます。"
                ),
            "V16" to (
                "それでさえ、その後さみんなでカラオケに行ったんだよね。" to
                    "それでさえ、その後さみんなでカラオケに行ったんだよね。"
                ),
        )

        for ((id, pair) in cases) {
            val (input, expected) = pair
            assertEquals("期待表 $id が一致しません", expected, VoiceFillerRemover.removeFillers(input))
        }
    }

    /** 相づちの「ええ」、否定の「いいえ」、語の一部の「え」を変更しないことを確認する。 */
    @Test
    fun keepsNonFillerExamplesUnchanged() {
        val unchanged = listOf(
            "いいえ、違います。",
            "ええ、そうです。",
            "考え方を変えた。",
            "まえに見えた家。",
            "カエルがかえる。",
            "いいえ",
            "ええ",
            "考え",
            "考えとく",
            "まえとあと",
            "ねえ、聞いて。",
            "へえ、すごいね。",
            "そうだねえ。",
            "それでさえ、難しい。",
            "答えと理由を教えて。",
            "あのうどん屋に行く。",
            "「えっと」を消す。",
            "いえ、大丈夫です。",
            "このまえ、行った店。",
            "へえー、すごい。",
            "新しいえ、製品です。",
        )

        for (sentence in unchanged) {
            assertEquals(sentence, VoiceFillerRemover.removeFillers(sentence))
        }
    }

    /** すべての対象フィラーが境界で除去され、読点の規則が保たれることを確認する。 */
    @Test
    fun removesAllTargetFillersWithCommaRules() {
        val cases = listOf(
            "えーっと、明日の予定" to "明日の予定",
            "ええっと明日の予定" to "明日の予定",
            "えーと、確認します。" to "確認します。",
            "えと、確認します。" to "確認します。",
            "えー、確認します。" to "確認します。",
            "あのー、すみません。" to "すみません。",
            "あのう、すみません。" to "すみません。",
            "午後はえと音声入力です。" to "午後は音声入力です。",
            "今日は晴れです。え、明日は雨です。" to "今日は晴れです。明日は雨です。",
            "ラーメン、え、また行こう。" to "ラーメン、また行こう。",
            "カレーえ、また食べたい。" to "カレー、また食べたい。",
            "ラーメンえ、えっと、また行こう。" to "ラーメン、また行こう。",
            "えっと、え、また行こう。" to "また行こう。",
        )

        for ((input, expected) in cases) {
            assertEquals(expected, VoiceFillerRemover.removeFillers(input))
        }
    }

    /** 話題としてのフィラー接尾辞が続くときはどのフィラーも残すことを確認する。 */
    @Test
    fun preservesTopicMentionsAcrossAllSuffixes() {
        val topicSentences = listOf(
            "えとか言わないで。",
            "えみたいな声が出た。",
            "えって言ったよね。",
            "えという音が聞こえた。",
            "えっていう口癖がある。",
            "えと言いました。",
            "えと呼びます。",
            "えっととか、えーっとみたいな言い方。",
            "あのーっていう言葉。",
            "あのうと言った。",
        )

        for (sentence in topicSentences) {
            assertEquals(sentence, VoiceFillerRemover.removeFillers(sentence))
        }
    }
}
